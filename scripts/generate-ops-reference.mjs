/**
 * Regenerate docs/reference/operations.mdx from the curated ops registry.
 * Run after `pnpm build`: pnpm docs:ops
 * With --check, fail instead of writing when the committed page is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ASC_OPS } from "../packages/core/dist/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCAL_FILE_ARGS = ["filePath", "outputPath"];

const groups = new Map();
for (const op of ASC_OPS) {
  if (!groups.has(op.group)) groups.set(op.group, []);
  groups.get(op.group).push(op);
}

const esc = (s) => s.replace(/\|/g, "\\|");
const args = (op) =>
  Object.entries(op.shape)
    .map(([k, s]) => (s.isOptional() ? `${k}?` : k))
    .join(", ");
const mode = (op) => {
  if (op.isWrite) return "read / **write**";
  return op.write ? "**write**" : "read";
};
const notes = (op) => {
  if (op.group === "accounts") return "local";
  if (LOCAL_FILE_ARGS.some((a) => a in op.shape)) return "CLI only";
  return "";
};

let out = `---
title: Operations reference
description: Every ASC_OPS operation, shared by the CLI (appstore ops call), MCP tools and the hosted API.
---

{/* Generated by scripts/generate-ops-reference.mjs. Do not edit by hand. */}

Every operation below is available as:

- an MCP tool with the same name (\`appstore-mcp\` and the hosted server)
- \`appstore ops call <name> '<json>'\`
- \`POST /v1/ops/<name>\` on the [hosted API](/mcp/hosted)

Write operations are marked **write** and need \`--confirm\` on the CLI. \`appstore_request\` is a write unless its method is \`GET\`.
Operations marked *CLI only* read or write local files and are not offered by the hosted server; *local* operations edit \`~/.config/appstore/config.json\`.

Total operations: **${ASC_OPS.length}**
`;

for (const [group, ops] of groups) {
  out += `\n## ${group}\n\n| Name | Mode | Arguments | Summary |\n|------|------|-----------|---------|\n`;
  for (const op of ops) {
    const n = notes(op);
    out += `| \`${op.name}\` | ${mode(op)}${n ? ` (${n})` : ""} | ${esc(args(op)) || "—"} | ${esc(op.summary)} |\n`;
  }
}

const target = join(root, "docs/reference/operations.mdx");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error("docs/reference/operations.mdx is out of date. Run: pnpm build && pnpm docs:ops");
    process.exit(1);
  }
  console.log("docs/reference/operations.mdx is up to date");
} else {
  writeFileSync(target, out);
  console.log(`Wrote docs/reference/operations.mdx (${ASC_OPS.length} operations)`);
}
