/**
 * Generate TypeScript types from Apple's official App Store Connect OpenAPI
 * specification.
 *
 *   pnpm generate:types                    # download the current spec from Apple
 *   pnpm generate:types --spec ./spec.json # use a spec file you already have
 *
 * Output:
 *   src/generated/app-store-connect.ts  (openapi-typescript output, committed)
 *   src/generated/spec-version.ts       (spec version + source URL)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { unzipSync, strFromU8 } from "fflate";
import openapiTS, { astToString } from "openapi-typescript";

export const SPEC_URL =
  "https://developer.apple.com/sample-code/app-store-connect/app-store-connect-openapi-specification.zip";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/generated");
const cacheDir = join(root, ".spec");

const { values } = parseArgs({
  options: { spec: { type: "string" } },
});

async function loadSpecText() {
  if (values.spec) return readFileSync(resolve(values.spec), "utf8");

  console.log(`Downloading ${SPEC_URL}`);
  const res = await fetch(SPEC_URL);
  if (!res.ok) throw new Error(`Spec download failed: HTTP ${res.status}`);
  const files = unzipSync(new Uint8Array(await res.arrayBuffer()));
  const name = Object.keys(files).find(
    (f) => f.endsWith(".json") && !f.startsWith("__MACOSX") && !f.includes("/._"),
  );
  if (!name) throw new Error("No JSON spec inside the downloaded archive");
  const text = strFromU8(files[name]);
  mkdirSync(cacheDir, { recursive: true });
  writeFileSync(join(cacheDir, "openapi.oas.json"), text);
  return text;
}

const specText = await loadSpecText();
const spec = JSON.parse(specText);
const version = spec.info?.version ?? "unknown";
const pathCount = Object.keys(spec.paths ?? {}).length;

const ast = await openapiTS(spec, { alphabetize: false, exportType: false });
const header = `/**
 * App Store Connect API types, generated by openapi-typescript from Apple's
 * official OpenAPI specification. Do not edit by hand: run \`pnpm generate:types\`.
 *
 * Spec version: ${version} (${pathCount} paths)
 */
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "app-store-connect.ts"), header + astToString(ast));
writeFileSync(
  join(outDir, "spec-version.ts"),
  `/** Version of the App Store Connect OpenAPI spec the generated types come from. */
export const ASC_SPEC_VERSION = ${JSON.stringify(version)};
/** Where \`pnpm generate:types\` downloads the spec. */
export const ASC_SPEC_URL = ${JSON.stringify(SPEC_URL)};
`,
);
console.log(`Generated types for App Store Connect API ${version} (${pathCount} paths)`);
