/**
 * Generate TypeScript types from Apple's official App Store Connect OpenAPI
 * specification.
 *
 *   pnpm generate:types                    # download the current spec from Apple
 *   pnpm generate:types --spec ./spec.json # use a spec file you already have
 *
 * Output:
 *   src/generated/app-store-connect.ts  (openapi-typescript output, committed)
 *   src/generated/spec-version.ts       (spec version + source URL)
 *
 * Then run `pnpm generate:ops` to refresh the generated operation table.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import openapiTS, { astToString } from "openapi-typescript";
import { CORE_ROOT, SPEC_URL, loadSpecText } from "./spec.mjs";

export { SPEC_URL };

const outDir = join(CORE_ROOT, "src/generated");

const { values } = parseArgs({
  options: { spec: { type: "string" } },
});

const { text: specText } = await loadSpecText({ spec: values.spec });
const spec = JSON.parse(specText);
const version = spec.info?.version ?? "unknown";
const pathCount = Object.keys(spec.paths ?? {}).length;

const ast = await openapiTS(spec, { alphabetize: false, exportType: false });
const header = `/**
 * App Store Connect API types, generated by openapi-typescript from Apple's
 * official OpenAPI specification. Do not edit by hand: run \`pnpm generate:types\`.
 *
 * Spec version: ${version} (${pathCount} paths)
 */
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "app-store-connect.ts"), header + astToString(ast));
writeFileSync(
  join(outDir, "spec-version.ts"),
  `/** Version of the App Store Connect OpenAPI spec the generated types come from. */
export const ASC_SPEC_VERSION = ${JSON.stringify(version)};
/** Where \`pnpm generate:types\` downloads the spec. */
export const ASC_SPEC_URL = ${JSON.stringify(SPEC_URL)};
`,
);
console.log(`Generated types for App Store Connect API ${version} (${pathCount} paths)`);
console.log("Next: pnpm generate:ops");
