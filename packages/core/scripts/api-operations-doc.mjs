/**
 * Render docs/reference/api-operations.mdx from the generated operation rows.
 * Shared by `pnpm generate:ops` (from the spec) and `pnpm check:generated`
 * (from the built table), so both produce byte-identical output.
 */

/**
 * @param {Array<{ name: string; group: string; method: string; path: string; write: boolean; deprecated: boolean }>} rows
 * @param {{ specVersion: string }} meta
 */
export function renderApiOperationsDoc(rows, meta) {
  const groups = new Map();
  for (const row of rows) {
    if (!groups.has(row.group)) groups.set(row.group, []);
    groups.get(row.group).push(row);
  }
  const names = [...groups.keys()].sort((a, b) => a.localeCompare(b));
  const byMethod = {};
  for (const row of rows) byMethod[row.method] = (byMethod[row.method] ?? 0) + 1;
  const methodLine = ["GET", "POST", "PATCH", "PUT", "DELETE"]
    .filter((m) => byMethod[m])
    .map((m) => `${m} ${byMethod[m]}`)
    .join(" · ");

  let out = `---
title: API operations reference
description: Every App Store Connect API operation, generated from Apple's OpenAPI spec ${meta.specVersion}.
---

{/* Generated by packages/core/scripts/generate-ops.mjs (pnpm generate:ops). Do not edit by hand. */}

One generated operation per path and method in Apple's App Store Connect OpenAPI spec **${meta.specVersion}**.
See [Full API coverage](/concepts/full-api-coverage) for how to search, describe and call them.

- Total operations: **${rows.length}** (${methodLine})
- Resource groups: **${names.length}**
- Call one: \`appstore api call <name> --param id=…\`, the MCP tool \`appstore_call_operation\`, or \`POST /v1/ops/<name>\` on the hosted API
- Write operations (anything but \`GET\`) are marked **write**: they need \`--confirm\` on the CLI and \`X-ASC-Allow-Writes: true\` on the hosted server

`;
  for (const group of names) {
    out += `\n## ${group}\n\n| Name | Method | Path | Mode |\n|------|--------|------|------|\n`;
    for (const row of groups.get(group)) {
      const mode = (row.write ? "**write**" : "read") + (row.deprecated ? " (deprecated)" : "");
      out += `| \`${row.name}\` | ${row.method} | \`${row.path}\` | ${mode} |\n`;
    }
  }
  return out;
}
